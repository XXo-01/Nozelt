import 'package:flutter/widgets.dart';

class NozeltL10n {
  const NozeltL10n(this.languageCode);

  final String languageCode;
  static const _russian = NozeltL10n('ru');
  static const _english = NozeltL10n('en');

  bool get isRussian => languageCode == 'ru';

  static NozeltL10n of(BuildContext context) =>
      Localizations.localeOf(context).languageCode == 'ru'
      ? _russian
      : _english;

  String text(String key, [Map<String, Object> args = const {}]) {
    var value =
        (_values[languageCode] ?? _values['en']!)[key] ??
        _values['en']![key] ??
        key;
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value.toString());
    }
    return value;
  }

  String nodeCount(int count) {
    if (!isRussian) return '$count ${count == 1 ? 'node' : 'nodes'}';
    final mod10 = count % 10;
    final mod100 = count % 100;
    final word = mod10 == 1 && mod100 != 11
        ? 'нода'
        : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)
        ? 'ноды'
        : 'нод';
    return '$count $word';
  }

  String dayCount(int count) {
    if (!isRussian) return '$count ${count == 1 ? 'day' : 'days'}';
    final mod10 = count % 10;
    final mod100 = count % 100;
    final word = mod10 == 1 && mod100 != 11
        ? 'день'
        : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)
        ? 'дня'
        : 'дней';
    return '$count $word';
  }

