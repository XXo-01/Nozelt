private data class StagedRuntimeReplacement(
    val previous: StoredVpnConfig,
    val replacement: StoredVpnConfig,
    val createdJournalId: String?,
    val baseline: Long,
)

/**
 * Thin adapter around the `binding.Binding` symbols generated by gomobile.
 *
 * Two distinct call sites use it:
 *  - [MainActivity] (from a coroutine on Dispatchers.Main) — needs the
 *    suspend wrappers so the Go calls run off the UI thread.
 *  - [NozeltVpnService] (already on a worker scope) — uses [startEngineSync]
 *    / [stopEngineSync] directly.
 *
 * It is intentionally an `object`: the Go engine itself is a process-wide
 * singleton, so wrapping it in a singleton on the Kotlin side mirrors that
 * constraint instead of inviting multiple instances that cannot coexist.
 */
object EngineBridge {

    @Volatile
    private var activeCore = VpnCore.MIHOMO
    internal val currentCore: VpnCore get() = activeCore

    private val nativeStartedAtMillis = AtomicLong(0L)
    private val nativeTraffic = NativeCoreTrafficTracker()

    private val loggerLock = Any()
    private var loggerImpl: LoggerImpl? = null
    private var fallbackLogger: LoggerImpl? = null
    private var loggerInstalled = false

    fun installLogger(impl: LoggerImpl) = synchronized(loggerLock) {
        if (loggerInstalled && loggerImpl === impl) return@synchronized
        loggerImpl = impl
        Binding.setLogger(impl)
        loggerInstalled = true
    }

    fun detachLogger(expected: LoggerImpl? = null) = synchronized(loggerLock) {
        if (!loggerInstalled || (expected != null && loggerImpl !== expected)) {
            return@synchronized
        }
        val fallback = fallbackLogger
        if (fallback != null && fallback !== expected) {
            Binding.setLogger(fallback)
            loggerImpl = fallback
            loggerInstalled = true
        } else {
            Binding.setLogger(null)
            loggerImpl = null
            loggerInstalled = false
        }
    }

    /** Debug-service logger retained underneath an optional UI log consumer. */
    fun installFallbackLogger(impl: LoggerImpl) = synchronized(loggerLock) {
        fallbackLogger = impl
        if (!loggerInstalled) {
            Binding.setLogger(impl)
            loggerImpl = impl
            loggerInstalled = true
        }
    }

    fun detachFallbackLogger(expected: LoggerImpl) = synchronized(loggerLock) {
        if (fallbackLogger !== expected) return@synchronized
        fallbackLogger = null
        if (loggerImpl === expected) {
            Binding.setLogger(null)
            loggerImpl = null
            loggerInstalled = false
        }
    }

    /**
     * Encrypts the rendered config in device-bound runtime storage, then asks
     * the VPN foreground service to establish the TUN and start the engine.
     * No proxy credential is placed in an Intent extra.
     */
    suspend fun start(
        context: Context,
        coreName: String,
        configYaml: String,
        tunOptionsJson: String?,
    ) {
        val core = VpnCore.fromWireName(coreName)
        val runtimeStore = SecureRuntimeConfigStore(context.applicationContext)
        val (previous, replacement) = withContext(Dispatchers.IO) {
            VpnProcessLifecycle.mutex.withLock {
                val previous = runtimeStore.read()
                previous to runtimeStore.write(core, configYaml, tunOptionsJson)
            }
        }
        val intent = Intent(context, NozeltVpnService::class.java).apply {
            action = NozeltVpnService.ACTION_START
        }
        try {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
                context.startForegroundService(intent)
            } else {
                context.startService(intent)
            }
        } catch (t: Throwable) {
            withContext(Dispatchers.IO) {
                VpnProcessLifecycle.mutex.withLock {
                    // Restore only if this failed dispatch still owns the
                    // encrypted generation. A newer concurrent start/reload
                    // must never be overwritten by this rollback.
                    val current = runtimeStore.read()
                    if (current?.requestId == replacement.requestId) {
                        if (previous == null) {
                            runtimeStore.delete()
                        } else {
                            runtimeStore.write(previous)
                        }
                    }
                }
            }
            throw t
        }
    }

    /**
     * Hands the Android TUN file descriptor to the Go engine. gomobile maps
     * Go `int` to a Java `long`, hence the widening. After this returns the
     * Go side owns the fd (see nozelt-core SetTunFd contract) — the caller
     * must not close it.
     */
    fun setTunFd(fd: Int) {
        Binding.setTunFd(fd.toLong())
    }

    /** Installs the per-socket VpnService.protect bridge before Go can dial. */
    fun installSocketProtector(protector: SocketProtector) {
        Binding.setSocketProtector(protector)
    }

    /** Detaches the VpnService callback after all Go transports are stopped. */
    fun detachSocketProtector() {
        Binding.setSocketProtector(null)
    }

    /** Asks the VPN foreground service to stop the engine and tear itself down. */
    fun stop(context: Context) {
        val intent = Intent(context, NozeltVpnService::class.java).apply {
            action = NozeltVpnService.ACTION_STOP
        }
        // Cannot use startForegroundService for the stop path — the service is
        // already running, a plain startService delivers the intent.
        context.startService(intent)
    }

    /** Requests a full TUN/core rebuild from the encrypted active config. */
    fun restart(context: Context) {
        val intent = Intent(context, NozeltVpnService::class.java).apply {
            action = NozeltVpnService.ACTION_RESTART
        }
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            context.startForegroundService(intent)
        } else {
            context.startService(intent)
        }
    }

    /**
     * Persists a replacement TUN/core config and requests one full restart.
     * Waits for and returns a strictly newer successful-start generation, so
     * the Dart host cannot mistake the old running status for completion.
     * Dispatch failure restores the encrypted config.
     */
    suspend fun restartWithConfig(
        context: Context,
        coreName: String,
        configYaml: String,
        tunOptionsJson: String?,
        rollbackKind: String?,
        rollbackPayload: String?,
    ): Long {
        val core = VpnCore.fromWireName(coreName)
        val runtimeStore = SecureRuntimeConfigStore(context.applicationContext)
        val rollbackStore = SecureRuntimeRollbackStore(context.applicationContext)
        val staged = withContext(Dispatchers.IO) {
            VpnProcessLifecycle.mutex.withLock {
                val stored = runtimeStore.read()
                    ?: error("active VPN config is missing")
                val journal = stageRollback(rollbackStore, rollbackKind, rollbackPayload)
                try {
                    StagedRuntimeReplacement(
                        previous = stored,
                        replacement = runtimeStore.writeActiveReplacement(
                            stored,
                            core,
                            configYaml,
                            tunOptionsJson,
                            journal?.id,
                        ),
                        createdJournalId = journal?.id,
                        baseline = VpnProcessLifecycle.generation.get(),
                    )
                } catch (t: Throwable) {
                    journal?.let { runCatching { rollbackStore.deleteIfId(it.id) } }
                    throw t
                }
            }
        }
        try {
            restart(context)
        } catch (t: Throwable) {
            withContext(Dispatchers.IO) {
                VpnProcessLifecycle.mutex.withLock {
                    runCatching {
                        runtimeStore.restoreIfCurrent(staged.replacement, staged.previous)
                    }
                        .exceptionOrNull()
                        ?.let(t::addSuppressed)
                    staged.createdJournalId?.let { journalId ->
                        runCatching { rollbackStore.deleteIfId(journalId) }
                            .exceptionOrNull()
                            ?.let(t::addSuppressed)
                    }
                }
            }
            throw t
        }
        repeat(160) {
            val current = VpnProcessLifecycle.generation.get()
            if (current > staged.baseline) return current
            delay(100)
        }
        error("replacement VPN session did not start")
    }

    suspend fun getStatusJson(): String = withContext(Dispatchers.IO) {
        if (activeCore == VpnCore.MIHOMO) {
            Binding.getStatus()
        } else {
            nativeStatusJson(activeCore)
        }
    }

    suspend fun getTrafficJson(): String = withContext(Dispatchers.IO) {
        getTrafficJsonSync()
    }

    fun getTrafficJsonSync(): String {
        if (activeCore == VpnCore.MIHOMO) return Binding.getTraffic()
        val traffic = nativeTraffic.sample()
        return JSONObject()
            .put("uploadBytes", traffic.uploadBytes)
            .put("downloadBytes", traffic.downloadBytes)
            .put("uploadSpeedBps", traffic.uploadSpeedBps)
            .put("downloadSpeedBps", traffic.downloadSpeedBps)
            .put("activeConnections", 0)
            .put("synthetic", false)
            .toString()
    }

    suspend fun getVersionJson(): String = withContext(Dispatchers.IO) {
        // Keep the established Dart wire shape. Per-profile core information
        // is exposed separately in profile state and diagnostics.
        Binding.getVersion()
    }

    /** Secret-preserving equality check used after Flutter/Activity restore. */
    suspend fun matchesRuntimeConfig(
        context: Context,
        coreName: String,
        configYaml: String,
        tunOptionsJson: String?,
    ): Boolean = withContext(Dispatchers.IO) {
        VpnProcessLifecycle.mutex.withLock {
            val current = SecureRuntimeConfigStore(context.applicationContext).read()
                ?: return@withLock false
            current.core == VpnCore.fromWireName(coreName) &&
                current.configYaml == configYaml &&
                current.tunOptionsJson == tunOptionsJson
        }
    }

    /**
     * Reads the cross-process journal after reconciling any operation that was
     * interrupted between two encrypted-file writes. A matching runtime with
     * no fallback is already the durable candidate; a matching restored
     * fallback must expose its old high-level snapshot. A journal that never
     * reached runtime storage is stale and cannot own a rollback.
     */
    internal suspend fun readRuntimeRollback(context: Context): StoredRuntimeRollback? =
        withContext(Dispatchers.IO) {
            VpnProcessLifecycle.mutex.withLock {
                val appContext = context.applicationContext
                val rollbackStore = SecureRuntimeRollbackStore(appContext)
                val journal = rollbackStore.readCurrent() ?: return@withLock null
                if (journal.rolledBack) return@withLock journal

                val runtimeStore = SecureRuntimeConfigStore(appContext)
                val runtime = runtimeStore.read()
                if (runtime?.rollbackJournalId != journal.id) {
                    check(rollbackStore.deleteIfId(journal.id)) {
                        "stale VPN rollback journal changed during reconciliation"
                    }
                    return@withLock null
                }
                if (runtime.fallbackRestored) {
                    check(rollbackStore.markRolledBackIfId(journal.id)) {
                        "VPN fallback journal changed during reconciliation"
                    }
                    return@withLock rollbackStore.readCurrent()
                }
                if (runtime.fallbackConfigYaml == null) {
                    check(rollbackStore.resolveSuccessfulIfId(journal.id)) {
                        "applied VPN rollback journal changed during reconciliation"
                    }
                    return@withLock null
                }
                // A stopped VPN cannot finish an interrupted replacement.
                // Restore its last known-good generation before Flutter loads
                // the matching high-level snapshot. Otherwise a pending
                // journal makes every cold start time out forever.
                if (!NozeltVpnService.isRequested(appContext)) {
                    val restored = runtimeStore.restoreFallbackIfCurrent(runtime)
                    if (restored != null) {
                        check(rollbackStore.markRolledBackIfId(journal.id)) {
                            "abandoned VPN rollback journal changed during reconciliation"
                        }
                        return@withLock rollbackStore.readCurrent()
                    }
                }
                journal
            }
        }

    suspend fun selectProxy(context: Context, groupName: String, proxyName: String) =
        withContext(Dispatchers.IO) {
            VpnProcessLifecycle.mutex.withLock {
                val runtimeStore = SecureRuntimeConfigStore(context.applicationContext)
                val previous = runtimeStore.read()
                    ?: error("active VPN config is missing")
                require(previous.core == VpnCore.MIHOMO) {
                    "live node selection requires a full ${previous.core.displayName} restart"
                }
                val replacement = runtimeStore.withSelectedProxy(
                    previous,
                    groupName,
                    proxyName,
                )
                runtimeStore.write(replacement)
                try {
                    Binding.selectProxy(groupName, proxyName)
                } catch (t: Throwable) {
                    runCatching { runtimeStore.write(previous) }
                        .exceptionOrNull()
                        ?.let(t::addSuppressed)
                    throw t
                }
            }
        }

    /**
     * Atomically hot-reloads rules/proxies and the encrypted recovery config.
     * The request id is preserved so a later STOP still deletes this session.
     * A native reload failure restores the previous encrypted generation.
     */
    suspend fun reloadConfig(
        context: Context,
        coreName: String,
        configYaml: String,
        tunOptionsJson: String?,
        rollbackKind: String?,
        rollbackPayload: String?,
    ) = withContext(Dispatchers.IO) {
        VpnProcessLifecycle.mutex.withLock {
            val runtimeStore = SecureRuntimeConfigStore(context.applicationContext)
            val rollbackStore = SecureRuntimeRollbackStore(context.applicationContext)
            val previous = runtimeStore.read()
                ?: error("active VPN config is missing")
            val core = VpnCore.fromWireName(coreName)
            require(core == VpnCore.MIHOMO && previous.core == VpnCore.MIHOMO) {
                "hot reload is available only for Mihomo"
            }
            val journal = stageRollback(rollbackStore, rollbackKind, rollbackPayload)
            val replacement = try {
                runtimeStore.writeActiveReplacement(
                    previous,
                    core,
                    configYaml,
                    tunOptionsJson,
                    journal?.id,
                )
            } catch (t: Throwable) {
                journal?.let { runCatching { rollbackStore.deleteIfId(it.id) } }
                throw t
            }
            try {
                Binding.reloadConfig(configYaml)
                check(confirmRuntimeConfigApplied(context, replacement)) {
                    "active VPN config changed during native reload"
                }
            } catch (t: Throwable) {
                runCatching { Binding.reloadConfig(previous.configYaml) }
                    .exceptionOrNull()
                    ?.let(t::addSuppressed)
                runCatching { runtimeStore.restoreIfCurrent(replacement, previous) }
                    .exceptionOrNull()
                    ?.let(t::addSuppressed)
                journal?.let {
                    runCatching { rollbackStore.deleteIfId(it.id) }
                        .exceptionOrNull()
                        ?.let(t::addSuppressed)
                }
                throw t
            }
        }
    }

    /**
     * Confirms a candidate after the core is running, resolving its separate
     * high-level rollback journal before removing metadata from runtime state.
     */
    internal fun confirmRuntimeConfigApplied(
        context: Context,
        applied: StoredVpnConfig,
    ): Boolean {
        val runtimeStore = SecureRuntimeConfigStore(context.applicationContext)
        if (!runtimeStore.markApplied(applied)) return false
        val journalId = applied.rollbackJournalId ?: return true
        val rollbackStore = SecureRuntimeRollbackStore(context.applicationContext)
        val journalHandled = if (applied.fallbackRestored) {
            rollbackStore.markRolledBackIfId(journalId)
        } else {
            rollbackStore.resolveSuccessfulIfId(journalId)
        }
        if (!journalHandled) return false
        return runtimeStore.clearRollbackMetadataIfCurrent(applied)
    }

    private fun stageRollback(
        store: SecureRuntimeRollbackStore,
        kind: String?,
        payload: String?,
    ): StoredRuntimeRollback? {
        if (kind == null && payload == null) return null
        require(!kind.isNullOrBlank() && !payload.isNullOrBlank()) {
            "runtime rollback kind and payload must be provided together"
        }
        return store.stage(kind, payload)
    }

    /** Parses one proxy share link via Go convert. Returns a JSON envelope. */
