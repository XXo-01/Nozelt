    @Volatile
    private var mihomoDataDirReady = false

    /**
     * Points Mihomo at the bundled GeoIP/GeoSite files (shared with Xray and
     * refreshed by the geodata updater). Without it GeoIP/GeoSite rules and
     * delay tests of such profiles fail on Android.
     */
    internal fun prepareMihomoDataDir(context: Context) {
        if (mihomoDataDirReady) return
        synchronized(this) {
            if (mihomoDataDirReady) return
            val directory = NativeCoreProcess.geodataDirectory(context.applicationContext)
            Binding.setDataDir(directory.absolutePath)
            mihomoDataDirReady = true
        }
    }

    /** Called from NozeltVpnService. Throws on Go error (mapped from `error`). */
    internal fun startEngineSync(
        context: Context,
        core: VpnCore,
        configYaml: String,
        selectedGroupName: String? = null,
        selectedProxyName: String? = null,
        tunFd: Int = -1,
    ) {
        activeCore = core
        if (core == VpnCore.MIHOMO) {
            nativeTraffic.stop()
            runCatching { prepareMihomoDataDir(context) }
                .onFailure { NozeltLog.w("EngineBridge", "could not prepare Mihomo geodata") }
            Binding.start(configYaml)
            if (selectedGroupName == null || selectedProxyName == null) return
            try {
                Binding.selectProxy(selectedGroupName, selectedProxyName)
            } catch (failure: Throwable) {
                // Start succeeded and owns the detached TUN fd. Return the bridge
                // to the same stopped/fd-released contract expected by the
                // service's start-failure path before surfacing selector failure.
                runCatching { Binding.stop() }.exceptionOrNull()?.let(failure::addSuppressed)
                throw failure
            }
            return
        }

        require(tunFd >= 0) { "native core TUN descriptor is missing" }
        val runtimeDirectory = File(context.noBackupFilesDir, "runtime").apply { mkdirs() }
        val configFile = File(runtimeDirectory, "active-${core.wireName}.json")
        try {
            configFile.writeText(configYaml, Charsets.UTF_8)
            configFile.setReadable(false, false)
            configFile.setReadable(true, true)
            NativeCoreProcess.start(context.applicationContext, core, configFile, tunFd)
            nativeStartedAtMillis.set(System.currentTimeMillis())
            nativeTraffic.start()
        } finally {
            // fork() copied the descriptor into the child. The service-side
            // duplicate and plaintext launch config are no longer needed.
            runCatching { ParcelFileDescriptor.adoptFd(tunFd).close() }
            runCatching { configFile.delete() }
        }
    }

    /** Called from NozeltVpnService. Throws on Go error. */
    fun stopEngineSync() {
        if (activeCore == VpnCore.MIHOMO) {
            Binding.stop()
        } else {
            NativeCoreProcess.stop()
            nativeStartedAtMillis.set(0L)
            nativeTraffic.stop()
        }
    }

    /** Technical stop that preserves FakeDNS mappings for the next Start. */
    fun stopEngineForRestartSync() {
        if (activeCore == VpnCore.MIHOMO) {
            Binding.stopForRestart()
        } else {
            NativeCoreProcess.stop()
            nativeStartedAtMillis.set(0L)
            nativeTraffic.stop()
        }
    }

    /** Rebuilds stale network transports while retaining the live TUN fd. */
    fun recoverNetworkSync() {
        if (activeCore == VpnCore.MIHOMO) {
            Binding.recoverNetwork()
        } else {
            error("${activeCore.displayName} requires a full restart after network change")
        }
    }

    /**
     * Mihomo can rebuild transports around a retained TUN descriptor. Native
     * Xray/sing-box processes cannot, so callers must restart them immediately
     * instead of spending time on guaranteed-to-fail recovery attempts.
     */
    fun supportsInPlaceNetworkRecovery(): Boolean = activeCore == VpnCore.MIHOMO

    /**
     * Sends one small request through the live Mihomo session's PROXY group,
     * reusing its existing transports. Throws when the path does not answer.
     * Native cores open a fresh outbound per flow, so only Mihomo needs it.
     */
    fun probeLiveConnectionSync(timeoutMs: Long) {
        check(activeCore == VpnCore.MIHOMO) { "live probe requires Mihomo" }
        Binding.probeLiveConnection(timeoutMs)
    }

    /** Cheap watchdog query used by the foreground service. */
    fun isEngineProcessRunning(): Boolean = if (activeCore == VpnCore.MIHOMO) {
        runCatching { JSONObject(Binding.getStatus()).optBoolean("running", false) }
            .getOrDefault(false)
    } else {
        NativeCoreProcess.isRunning()
    }

    private fun nativeStatusJson(core: VpnCore): String {
        val running = NativeCoreProcess.isRunning()
        val startedMillis = nativeStartedAtMillis.get()
        val startedSeconds = if (running && startedMillis > 0L) startedMillis / 1000L else 0L
        val uptime = if (running && startedMillis > 0L) {
            ((System.currentTimeMillis() - startedMillis) / 1000L).coerceAtLeast(0L)
        } else {
            0L
        }
        return JSONObject()
            .put("running", running)
            .put("startedAtUnix", startedSeconds)
            .put("uptimeSeconds", uptime)
            .put("mihomoVersion", if (core == VpnCore.XRAY) "Xray 26.9.9" else "sing-box 1.14.1")
            .put("nozeltCoreVersion", "android-multicore-1")
            .put("mode", "")
            .put("listeners", JSONObject())
            .put("connectionsCount", 0)
            .put(
                "tun",
                JSONObject()
                    .put("enabled", running)
                    .put("stack", "gvisor")
                    .put("fd", if (running) 3 else 0),
            )
            .put("openFileDescriptors", -1)
            .put("goRoutines", 0)
            // Native cores run in Nozelt's excluded transport process/UID.
            // This is the native-core equivalent of per-socket protect().
            .put("socketProtection", running)
            .put("protectedSockets", 0)
            .put("protectionFailures", 0)
            .toString()
    }
}
