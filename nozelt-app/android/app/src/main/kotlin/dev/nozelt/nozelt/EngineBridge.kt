    fun parseSubscription(content: String): String = Binding.parseSubscription(content)

    /** Runs real mihomo URL tests through the active protected VPN context. */
    fun testProxyDelays(
        configYaml: String,
        namesJson: String,
        testUrl: String,
        timeoutMs: Long,
        onResult: ((String, Int?) -> Unit)? = null,
    ): String {
        if (onResult == null) {
            return Binding.testProxyDelays(configYaml, namesJson, testUrl, timeoutMs)
        }
        return Binding.testProxyDelaysStream(
            configYaml,
            namesJson,
            testUrl,
            timeoutMs,
            object : DelayListener {
                override fun onResult(name: String, delay: Long) {
                    onResult(name, delay.toInt().takeIf { it > 0 })
                }
            },
        )
    }

    /** Runs a direct test only when Android has confirmed that VPN is off. */
    fun testProxyDelaysOffline(
        configYaml: String,
        namesJson: String,
        testUrl: String,
        timeoutMs: Long,
        onResult: ((String, Int?) -> Unit)? = null,
    ): String {
        if (onResult == null) {
            return Binding.testProxyDelaysOffline(configYaml, namesJson, testUrl, timeoutMs)
        }
        return Binding.testProxyDelaysOfflineStream(
            configYaml,
            namesJson,
            testUrl,
            timeoutMs,
            object : DelayListener {
                override fun onResult(name: String, delay: Long) {
                    onResult(name, delay.toInt().takeIf { it > 0 })
                }
            },
        )
    }

